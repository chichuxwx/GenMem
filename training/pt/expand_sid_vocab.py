"""
expand_sid_vocab.py

Expand a base model's vocabulary with SID tokens for MemRetriever/MemEvolver training.

Given a sid_config.json (generated by train_from_experience.py or manually created),
this script:
  1. Loads the base tokenizer
  2. Generates SID tokens: <SID_L1_0>, <SID_L1_1>, ..., <SID_L3_N>
  3. Adds them as special tokens
  4. Resizes model embeddings
  5. Saves expanded model + tokenizer + sid_token_ids.json

Usage:
    python expand_sid_vocab.py \
        --base_tokenizer Qwen/Qwen2.5-0.5B \
        --base_model Qwen/Qwen2.5-0.5B \
        --sid_config ./rqkmeans_model/sid_config.json \
        --output_dir ./model_with_sid
"""

import json
import argparse
from pathlib import Path

import torch
from transformers import AutoTokenizer, AutoModelForCausalLM


def build_sid_tokens_from_config(cfg: dict):
    """Generate SID token strings from config.

    Config format:
        {"L1": 2048, "L2": 1024, "L3": 512}
    or:
        {"L1": [0, 1, 2, ...], "L2": [...], "L3": [...]}

    Returns:
        List of token strings, e.g. ["<SID_L1_0>", "<SID_L1_1>", ...]
    """
    tokens = []
    for level in sorted(cfg.keys()):
        if not level.startswith("L"):
            continue
        val = cfg[level]
        if isinstance(val, int):
            for i in range(val):
                tokens.append(f"<SID_{level}_{i}>")
        elif isinstance(val, list):
            for i in val:
                tokens.append(f"<SID_{level}_{i}>")
        else:
            raise ValueError(f"Unsupported config format for {level}: {val}")
    return tokens


def main():
    parser = argparse.ArgumentParser(
        description="Expand model vocabulary with SID tokens",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--base_tokenizer", type=str, required=True,
        help="Base tokenizer path or HuggingFace name",
    )
    parser.add_argument(
        "--base_model", type=str, required=True,
        help="Base model path or HuggingFace name",
    )
    parser.add_argument(
        "--sid_config", type=str, required=True,
        help="SID config JSON file (from train_from_experience.py output or manual)",
    )
    parser.add_argument(
        "--output_dir", type=str, required=True,
        help="Output directory for expanded model + tokenizer",
    )
    args = parser.parse_args()

    print("\n" + "=" * 40)
    print("Step 1. Load Tokenizer")
    print("=" * 40)

    tokenizer = AutoTokenizer.from_pretrained(
        args.base_tokenizer,
        use_fast=True,
        trust_remote_code=True,
    )
    original_vocab_size = len(tokenizer)
    print(f"Original vocab size: {original_vocab_size}")

    print("\n" + "=" * 40)
    print("Step 2. Build SID Tokens")
    print("=" * 40)

    with open(args.sid_config, "r") as f:
        sid_cfg = json.load(f)

    sid_tokens = build_sid_tokens_from_config(sid_cfg)
    print(f"SID tokens defined: {len(sid_tokens)}")

    vocab = tokenizer.get_vocab()
    new_tokens = [t for t in sid_tokens if t not in vocab]
    print(f"New tokens to add: {len(new_tokens)}")

    existing = tokenizer.special_tokens_map.get("additional_special_tokens", [])
    # Preserve any existing additional_special_tokens and merge with new ones
    if isinstance(existing, str):
        existing = [existing]
    merged = list(existing) + [t for t in new_tokens if t not in existing]
    num_added = tokenizer.add_special_tokens(
        {"additional_special_tokens": merged},
    )
    print(f"Tokenizer added tokens: {num_added}")

    new_vocab_size = len(tokenizer)
    print(f"New vocab size: {new_vocab_size}")

    print("\n" + "=" * 40)
    print("Step 3. Load Base Model")
    print("=" * 40)

    model = AutoModelForCausalLM.from_pretrained(
        args.base_model,
        torch_dtype="auto",
        device_map=None,  # Do NOT use auto during resize
        trust_remote_code=True,
        low_cpu_mem_usage=True,
    )
    old_embed_size = model.get_input_embeddings().weight.shape[0]
    print(f"Model embedding size: {old_embed_size}")

    print("\n" + "=" * 40)
    print("Step 4. Resize Embedding")
    print("=" * 40)

    if old_embed_size != new_vocab_size:
        print(f"Resizing embeddings: {old_embed_size} -> {new_vocab_size}")
        model.resize_token_embeddings(new_vocab_size, mean_resizing=True)
    else:
        print("Embedding already matches tokenizer")

    print("\n" + "=" * 40)
    print("Step 5. Compute SID token ids")
    print("=" * 40)

    sid_token_ids = {}
    for token in sid_tokens:
        sid_token_ids[token] = tokenizer.convert_tokens_to_ids(token)

    sid_ids = list(sid_token_ids.values())
    print(f"SID token id range: {min(sid_ids)} - {max(sid_ids)}")

    print("\n" + "=" * 40)
    print("Step 6. Save Model & Tokenizer")
    print("=" * 40)

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    tokenizer.save_pretrained(output_dir)
    model.save_pretrained(
        output_dir,
        safe_serialization=True,
        max_shard_size="5GB",
    )

    with open(output_dir / "sid_tokens.txt", "w") as f:
        for t in sid_tokens:
            f.write(t + "\n")

    with open(output_dir / "sid_token_ids.json", "w") as f:
        json.dump(sid_token_ids, f, indent=2)

    print(f"\nSaved files:")
    print(f"  {output_dir / 'sid_tokens.txt'}")
    print(f"  {output_dir / 'sid_token_ids.json'}")

    print("\n" + "=" * 40)
    print("DONE")
    print("=" * 40)
    print(f"Output directory: {output_dir.absolute()}")
    print(f"\nSID token id range: {min(sid_ids)} - {max(sid_ids)}")
    print(f"Training tip: only compute loss on SID tokens:")
    print(f"  sid_logits = logits[..., {min(sid_ids)}:{max(sid_ids) + 1}]")


if __name__ == "__main__":
    main()
